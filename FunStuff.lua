local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Library = require(ReplicatedStorage:WaitForChild("Framework"):WaitForChild("Library"))
local Connection = Library.GetConnection()

local function getDevProducts()
    local products = {}
    local pages = MarketplaceService:GetDeveloperProductsAsync()
    
    while true do
        for _, product in pairs(pages:GetCurrentPage()) do
            table.insert(products, {
                id = product.ProductId,
                name = product.Name,
                price = product.PriceInRobux or 0
            })
        end
        
        if pages.IsFinished then break end
        pages:AdvanceToNextPageAsync()
    end
    
    return products
end

local localPlayer = Players.LocalPlayer
local allProducts = getDevProducts()

local function getRemote()
    local gameRemotes = ReplicatedStorage:FindFirstChild("GameRemotes")
    if not gameRemotes then
        gameRemotes = ReplicatedStorage:WaitForChild("GameRemotes", 5)
    end
    if not gameRemotes then return nil end
    
    local remotes = {}
    for _, child in pairs(gameRemotes:GetChildren()) do
        if child:IsA("RemoteEvent") then
            table.insert(remotes, child)
        end
    end
    
    if #remotes > 0 then
        return remotes[math.random(1, #remotes)]
    end
    
    local allChildren = gameRemotes:GetChildren()
    if #allChildren > 0 then
        return allChildren[math.random(1, #allChildren)]
    end
    
    return nil
end

local remoteEvent = getRemote()

local function fireRemote(args)
    if not remoteEvent then
        remoteEvent = getRemote()
    end
    if remoteEvent then
        local success, err = pcall(function()
            remoteEvent:FireServer(unpack(args))
        end)
        if not success then
            remoteEvent = getRemote()
            if remoteEvent then
                pcall(function()
                    fireRemote(args)
                end)
            end
        end
    end
end

local function findProductByName(name)
    for _, product in pairs(allProducts) do
        if product.name == name then
            return product.id
        end
    end
    return nil
end

